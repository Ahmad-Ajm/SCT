function sctDict() {
  const lang = (document.documentElement.lang === "en") ? "en" : "ar";
  return I18N[lang] || I18N.ar;
}

// مترجم متاح للسكربتات المضمّنة (للنصوص المولّدة ديناميكياً)
window.sctT = function (key, fallback) {
  const d = sctDict();
  return d[key] !== undefined ? d[key] : (fallback !== undefined ? fallback : key);
};

// قوائم تتبع لغة الواجهة (مثل لغة التقرير): تتبع لغة الواجهة تلقائياً ما لم
// يغيّرها المستخدم يدوياً (data-i18n-followlang). يبقى الخيار قابلاً للتعديل.
function sctSyncFollowLang(lang) {
  document.querySelectorAll("select[data-i18n-followlang]").forEach((sel) => {
    if (sel.dataset.userset === "1") return;             // المستخدم اختار يدوياً
    if ([...sel.options].some((o) => o.value === lang)) sel.value = lang;
  });
}

function sctApplyLang(lang) {
  const dict = I18N[lang] || I18N.ar;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const k = el.getAttribute("data-i18n");
    if (dict[k] !== undefined) el.textContent = dict[k];
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    const k = el.getAttribute("data-i18n-ph");
    if (dict[k] !== undefined) el.setAttribute("placeholder", dict[k]);
  });
  sctSyncFollowLang(lang);
  const btn = document.getElementById("langToggle");
  if (btn) btn.textContent = dict.lang_btn;
  try { localStorage.setItem("sct_lang", lang); } catch (e) {}
  // إشعار للسكربتات كي تُعيد رسم النصوص المولّدة (شريط السرعة، التنزيلات…)
  document.dispatchEvent(new CustomEvent("sct:langchange", { detail: { lang } }));
}

function sctInitLang() {
  let lang = "ar";
  try { lang = localStorage.getItem("sct_lang") || "ar"; } catch (e) {}
  sctApplyLang(lang);
  // علِّم قوائم تتبع اللغة عند تعديل المستخدم لها يدوياً كي نتوقّف عن المزامنة
  document.querySelectorAll("select[data-i18n-followlang]").forEach((sel) => {
    sel.addEventListener("change", () => { sel.dataset.userset = "1"; });
  });
  const btn = document.getElementById("langToggle");
  if (btn) {
    btn.addEventListener("click", () => {
      const cur = document.documentElement.lang === "ar" ? "en" : "ar";
      sctApplyLang(cur);
    });
  }
}

document.addEventListener("DOMContentLoaded", sctInitLang);
